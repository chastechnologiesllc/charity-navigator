const bySlug = new Map(CHARITIES.map((c) => [c.slug, c]));

export function getCharity(slug: string) {
  return bySlug.get(slug);
}

export function charitiesBySlugs(slugs: string[]) {
  return slugs.map((s) => bySlug.get(s)).filter((c): c is Charity => Boolean(c));
}

export function similarCharities(charity: Charity, limit = 3) {
  return CHARITIES.filter((c) => c.slug !== charity.slug && c.cause === charity.cause)
    .sort((a, b) => b.overall - a.overall)
    .slice(0, limit);
}

export function searchCharities(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return CHARITIES;
  const tokens = q.split(/\s+/).filter(Boolean);
  return CHARITIES.map((c) => {
    const hay = `${c.name} ${c.ein} ${c.city} ${c.state} ${c.cause} ${c.tags.join(" ")} ${c.mission} ${c.programs.join(" ")}`.toLowerCase();
    let score = 0;
    if (c.name.toLowerCase().includes(q)) score += 50;
    if (c.ein.replace(/\D/g, "").includes(q.replace(/\D/g, "")) && q.replace(/\D/g, "").length >= 4) score += 40;
    for (const t of tokens) {
      if (hay.includes(t)) score += 8;
      if (c.tags.some((tag) => tag.includes(t))) score += 6;
    }
    return { c, score };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || b.c.overall - a.c.overall)
    .map((x) => x.c);
}
